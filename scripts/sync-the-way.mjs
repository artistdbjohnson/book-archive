#!/usr/bin/env node
/*
  The Way -> archive.js sync.

  Source of truth for the published text is content/the-way/the-way-chNN.md
  (one file per chapter, "# Chapter One" heading, plain paragraphs).
  This script rebuilds the generated The Way entry inside BOOKS in archive.js
  (between the the-way:begin / the-way:end markers) and bumps the offline
  cache version in sw.js whenever archive.js changes, the same way every
  other archive update ships with a new SW version.

  Usage:
    node scripts/sync-the-way.mjs
        Rebuild archive.js from content/the-way/*.md.
    node scripts/sync-the-way.mjs --from /workspace/writing-corpus/the-way/manuscript --through 6
        Copy the-way-ch01.md .. the-way-ch06.md from the manuscript folder into
        content/the-way/ first (prose copied byte for byte), then rebuild.
        Only chapters 1..N are published; anything past N is removed from content/.
    node scripts/sync-the-way.mjs --check
        Exit 1 if archive.js is out of date with content/the-way/ (changes nothing).
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = path.join(ROOT, 'content', 'the-way');
const ARCHIVE = path.join(ROOT, 'archive.js');
const SW = path.join(ROOT, 'sw.js');

const BOOK = {
  id: 'the-way',
  title: 'The Way',
  subtitle: 'Douglxss Burley Johnson / d.b.j.',
  series: 'The Way',
  year: 2026,
  type: 'Fiction',
  plannedChapters: 36,
  blurb: "Eli took the tolls at Jerusalem's north gate. He'd known Stephen since they were boys, and the afternoon they stoned him outside the wall, Eli was right there in the crowd with somebody's arm across his chest. After that they started writing names down, and his was one of them."
};
const BEGIN = '/* the-way:begin - generated by scripts/sync-the-way.mjs from content/the-way/*.md. Do not edit by hand. */';
const END = '/* the-way:end */';

const args = process.argv.slice(2);
const opt = name => { const i = args.indexOf(name); return i < 0 ? null : (args[i + 1] || ''); };
const has = name => args.includes(name);
const pad = n => String(n).padStart(2, '0');
const fileFor = n => `the-way-ch${pad(n)}.md`;

function die(msg){ console.error('sync-the-way: ' + msg); process.exit(1); }

function importFrom(dir, through){
  if(!Number.isInteger(through) || through < 1) die('--through must be a chapter number (1 or more)');
  if(!fs.existsSync(dir)) die('no such folder: ' + dir);
  fs.mkdirSync(CONTENT, { recursive: true });
  for(let n = 1; n <= through; n++){
    const src = path.join(dir, fileFor(n));
    if(!fs.existsSync(src)) die('missing ' + src);
    fs.copyFileSync(src, path.join(CONTENT, fileFor(n)));
  }
  for(const f of fs.readdirSync(CONTENT)){
    const m = /^the-way-ch(\d+)\.md$/.exec(f);
    if(m && Number(m[1]) > through){ fs.unlinkSync(path.join(CONTENT, f)); console.log('unpublished ' + f); }
  }
}

function readChapters(){
  if(!fs.existsSync(CONTENT)) die('no content folder: ' + CONTENT);
  const nums = fs.readdirSync(CONTENT).map(f => /^the-way-ch(\d+)\.md$/.exec(f)).filter(Boolean).map(m => Number(m[1])).sort((a, b) => a - b);
  if(!nums.length) die('no chapter files in ' + CONTENT);
  nums.forEach((n, i) => { if(n !== i + 1) die('chapters must run 1..N with no gaps; found ch' + pad(n) + ' at position ' + (i + 1)); });
  return nums.map(n => {
    const raw = fs.readFileSync(path.join(CONTENT, fileFor(n)), 'utf8').replace(/\r\n?/g, '\n');
    const m = /^#\s+(.+?)\s*\n([\s\S]*)$/.exec(raw.replace(/^\uFEFF/, '').trimStart());
    if(!m) die(fileFor(n) + ' must start with a "# Chapter ..." heading');
    const label = m[1].trim();
    const body = m[2].trim().replace(/\n{3,}/g, '\n\n');
    if(!body) die(fileFor(n) + ' has no text');
    return { label, text: label + '\n\n' + body };
  });
}

function entry(chapters){
  const n = chapters.length;
  const list = [{ label: 'Front Matter', text: BOOK.title + '\n\nby Douglxss Burley Johnson / d.b.j.' }].concat(chapters);
  const head = `{id:${JSON.stringify(BOOK.id)}, title:${JSON.stringify(BOOK.title)}, subtitle:${JSON.stringify(BOOK.subtitle)}, series:${JSON.stringify(BOOK.series)}, year:${BOOK.year}, type:${JSON.stringify(BOOK.type)}, status:${JSON.stringify('In progress \u00b7 ' + n + ' of ' + BOOK.plannedChapters + ' chapters')}, freeChapterCount:${list.length}, blurb:${JSON.stringify(BOOK.blurb)}, chapters:[`;
  const rows = list.map(c => `      {label:${JSON.stringify(c.label)}, text:${JSON.stringify(c.text)}}`).join(',\n');
  return `  ${BEGIN}\n  ${head}\n${rows}\n    ]},\n  ${END}`;
}

function bumpSw(n){
  let sw = fs.readFileSync(SW, 'utf8');
  const m = /dglxss-archive-sw-v(\d+)/.exec(sw);
  if(!m) die('could not find the cache version in sw.js');
  const next = Number(m[1]) + 1;
  sw = sw.replace(/dglxss-archive-sw-v\d+/, 'dglxss-archive-sw-v' + next)
         .replace('/* Offline cache. ', `/* Offline cache. v${next} refreshes the shell for The Way, chapters 1-${n}. `);
  fs.writeFileSync(SW, sw);
  return next;
}

const from = opt('--from');
if(from !== null) importFrom(path.resolve(from), Number(opt('--through')));
else if(has('--through')) die('--through needs --from <manuscript folder>');

const chapters = readChapters();
const archive = fs.readFileSync(ARCHIVE, 'utf8');
const a = archive.indexOf(BEGIN), b = archive.indexOf(END);
if(a < 0 || b < a) die('markers not found in archive.js');
const start = archive.lastIndexOf('\n', a) + 1;
const next = archive.slice(0, start) + entry(chapters) + archive.slice(b + END.length);

if(has('--check')){
  if(next !== archive){ console.error('archive.js is out of date: run node scripts/sync-the-way.mjs'); process.exit(1); }
  console.log('archive.js is current: The Way, ' + chapters.length + ' chapters');
  process.exit(0);
}
if(next === archive){ console.log('No change: The Way already has ' + chapters.length + ' chapters in archive.js'); process.exit(0); }
fs.writeFileSync(ARCHIVE, next);
const v = bumpSw(chapters.length);
console.log('The Way: ' + chapters.length + ' chapters written to archive.js; sw.js cache now v' + v);
chapters.forEach(c => console.log('  ' + c.label + ' (' + (c.text.match(/\S+/g) || []).length + ' words)'));
